    switch (language) {
      case AppLanguage.hindi:
        return _hindi;

      case AppLanguage.marathi:
        return _marathi;

      case AppLanguage.bengali:
        return _bengali;

      case AppLanguage.assamese:
        return _assamese;

      case AppLanguage.english:
        return _english;
    }
  }
